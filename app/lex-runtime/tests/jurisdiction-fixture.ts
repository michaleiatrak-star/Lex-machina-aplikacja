export function writeJurisdictionManifest(root: string, modules: Record<string, string> = FIXTURE_JURISDICTION): void {
  const dir = path.join(root, "prawo-polskie-v2");
  fs.mkdirSync(dir, { recursive: true });
  const lines = Object.entries(modules).map(([key, module]) => `| \`${key}\` | \`${module}\` | test |`);
  fs.writeFileSync(path.join(dir, "JURYSDYKCJA.md"), ["| Klucz | Moduł | Zakres |", "|---|---|---|", ...lines, ""].join("\n"));
}
